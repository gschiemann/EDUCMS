const perDimension = await pipeline(
  DIMENSIONS,
  (d) => agent(finderPrompt(d), {
    label: 'find:' + d.key,
    phase: 'Recon',
    schema: FINDINGS_SCHEMA,
    effort: 'high',
  }),
  (res, d) => {
    if (!res || !Array.isArray(res.findings)) {
      log('WARNING: finder ' + d.key + ' returned no usable payload')
      return { key: d.key, title: d.title, dead: true, verified: [], existingDefenses: [], posture: 'UNKNOWN', surfacesChecked: [], surfacesNotChecked: ['ENTIRE DIMENSION — finder agent failed'] }
    }
    const worth = res.findings.filter(f => f.severity !== 'INFO')
    const dropped = res.findings.length - worth.length
    if (dropped > 0) log(d.key + ': ' + dropped + ' INFO-level findings recorded but not sent to verification')
    const base = {
      key: d.key, title: d.title, raw: res.findings,
      existingDefenses: res.existingDefenses || [],
      posture: res.overallPosture,
      postureRationale: res.postureRationale,
      surfacesChecked: res.surfacesChecked || [],
      surfacesNotChecked: res.surfacesNotChecked || [],
    }
    if (worth.length === 0) return Object.assign({}, base, { verified: [] })
    return parallel(worth.map(f => () =>
      agent(refutePrompt(d, f), {
        label: 'refute:' + f.id,
        phase: 'Verify',
        schema: VERDICT_SCHEMA,
        effort: 'high',
      }).then(v => Object.assign({}, f, { dimension: d.key, verdict: v }))
    )).then(vs => Object.assign({}, base, { verified: vs.filter(Boolean) }))
  }
)

