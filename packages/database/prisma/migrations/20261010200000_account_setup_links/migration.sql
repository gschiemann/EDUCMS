-- 2026-10-10 — ONE-TIME ACCOUNT SETUP LINKS.
--
-- WHY. The provisioned location accounts (RIOT: 41) were handed STARTER PASSWORDS derived from
-- public postal codes. An admin now hands each person a single-use, expiring link instead;
-- generating one retires the starter password (an unknown random hash replaces it) and ends every
-- session, and redeeming it signs the person straight into first-login setup. Only sha256(token) is
-- stored; the token itself is shown once, to the admin who generated it.
--
-- ADDITIVE AND NON-DESTRUCTIVE: one brand-new table, three indexes, one foreign key. Nothing existing
-- is altered. The FK only REFERENCES "users": adding it takes SHARE ROW EXCLUSIVE on "users", which
-- does not block reads, and the new table is empty so validation is instant. lock_timeout keeps even
-- that brief lock from queueing behind a long transaction on "users" (every sign-in reads it).
--
-- IDEMPOTENT because the dev flow is `pnpm db:push`: IF NOT EXISTS on the table and every index, and
-- the foreign key behind a pg_constraint guard, so a database that already took this shape applies
-- the file as a no-op.
--
-- DDL generated by Prisma (`migrate diff --from-schema-datamodel <47f9b8ff> --to-schema-datamodel
-- <this commit> --script`) and then made idempotent — the column list is unchanged from its output.

SET lock_timeout = '5s';

CREATE TABLE IF NOT EXISTS "account_setup_links" (
    "id" TEXT NOT NULL,
    "tenant_id" TEXT NOT NULL,
    "user_id" TEXT NOT NULL,
    "token_hash" TEXT NOT NULL,
    "created_by_id" TEXT NOT NULL,
    "expires_at" TIMESTAMP(3) NOT NULL,
    "used_at" TIMESTAMP(3),
    "revoked_at" TIMESTAMP(3),
    "created_at" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "account_setup_links_pkey" PRIMARY KEY ("id")
);

-- The link's token → its row (single lookup on preview / redeem).
CREATE UNIQUE INDEX IF NOT EXISTS "account_setup_links_token_hash_key"
  ON "account_setup_links"("token_hash");

-- "Retire this account's older links" + the per-account link status on the People page.
CREATE INDEX IF NOT EXISTS "account_setup_links_user_id_idx"
  ON "account_setup_links"("user_id");

-- Tenant-scoped reads.
CREATE INDEX IF NOT EXISTS "account_setup_links_tenant_id_idx"
  ON "account_setup_links"("tenant_id");

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'account_setup_links_user_id_fkey'
  ) THEN
    ALTER TABLE "account_setup_links"
      ADD CONSTRAINT "account_setup_links_user_id_fkey"
      FOREIGN KEY ("user_id") REFERENCES "users"("id")
      ON DELETE CASCADE ON UPDATE CASCADE;
  END IF;
END $$;
