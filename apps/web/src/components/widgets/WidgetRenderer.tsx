// TICKER — Animated scrolling marquee
// ═══════════════════════════════════════════════════════

function TickerWidget({ config }: { config: any }) {
  // Phase 3 field-mapping — "Custom data" feed. When the template's
  // Driven-by picker set this ticker live (config.customSync), pull rows
  // from the operator's REST/CSV feed via the SSRF-gated proxy and scroll
  // the chosen column as the ticker items. Called unconditionally (Rules
  // of Hooks) — it no-ops + returns null when customSync is off, so themed
  // tickers below are unaffected. The live override only applies to the
  // default (unthemed) ticker; themed tickers stay on their static copy
  // (documented limitation — they bake their own layout).
  const customRows = useCustomData(
    !!config.customSync,
    typeof config.customUrl === 'string' ? config.customUrl : '',
    config.customFormat === 'csv' ? 'csv' : 'json',
  );

  if (config.theme === 'gym-pe') return <GymPETicker config={config} />;
  if (config.theme === 'principals-office') return <PrincipalsOfficeTicker config={config} />;
  if (config.theme === 'office-dashboard') return <OfficeDashboardTicker config={config} />;
  if (config.theme === 'back-to-school') return <BackToSchoolTicker config={config} />;
  if (config.theme === 'bus-loop') return <BusLoopTicker config={config} />;
  if (config.theme === 'diner-chalkboard') return <DinerChalkboardTicker config={config} />;
  if (config.theme === 'rainbow-animated') return <RainbowAnimatedTicker config={config} />;
  if (config.theme === 'rainbow-ribbon') return <RainbowRibbonTicker config={config} />;
  if (config.theme === 'field-day') return <FieldDayTicker config={config} />;
  if (config.theme === 'bulletin-board') return <BulletinBoardTicker config={config} />;
  if (config.theme === 'storybook') return <StorybookTicker config={config} />;
  if (config.theme === 'scrapbook') return <ScrapbookTicker config={config} />;
  if (config.theme === 'track-day') return <TrackDayTicker config={config} />;
  if (config.theme === 'scorebug') return <ScorebugTicker config={config} />;
  if (config.theme === 'jumbotron-pro') return <JumbotronProTicker config={config} />;
  if (config.theme === 'locker-hallway') return <LockerHallwayTicker config={config} />;
  if (config.theme === 'spirit-rally') return <SpiritRallyTicker config={config} />;
  if (config.theme === 'stem-lab') return <StemLabTicker config={config} />;
  if (config.theme === 'morning-news') return <MorningNewsTicker config={config} />;
  if (config.theme === 'art-studio') return <ArtStudioTicker config={config} />;
  if (config.theme === 'varsity-athletic') return <VarsityAthleticTicker config={config} />;
  if (config.theme === 'senior-countdown') return <SeniorCountdownTicker config={config} />;
  if (config.theme === 'news-studio-pro') return <NewsStudioProTicker config={config} />;
  if (config.theme === 'campus-quad') return <CampusQuadTicker config={config} />;
  if (config.theme === 'achievement-hall') return <AchievementHallTicker config={config} />;
  if (config.theme === 'final-chance') return <FinalChanceTicker config={config} />;
  if (config.theme === 'high-school-athletics') return <AthleticsTicker config={config} />;
  if (config.theme === 'library-quiet') return <LibraryQuietTicker config={config} />;
  if (config.theme === 'middle-school-hall') return <MSHallTicker config={config} />;
  if (config.theme === 'music-arts') return <MusicArtsTicker config={config} />;
  if (config.theme === 'stem-science') return <StemScienceTicker config={config} />;
  if (config.theme === 'sunshine-academy') return <SunshineAcademyTicker config={config} />;
  // Phase 3 — when a live custom feed is present, scroll the chosen column
  // (config.customColumn) from each row as the ticker items. Falls back to
  // the first text-ish column when none is chosen, then to the static
  // messages if the feed is empty / hasn't loaded / errored (useCustomData
  // returns null before the first good fetch, so the ticker never blanks).
  const liveMessages = (() => {
    if (!config.customSync || !customRows || customRows.length === 0) return null;
    const col = typeof config.customColumn === 'string' && config.customColumn
      ? config.customColumn
      : pickDefaultColumn(customRows[0]);
    if (!col) return null;
    const out = customRows
      .map((r) => (r && typeof r[col] === 'string' ? r[col].trim() : ''))
      .filter(Boolean);
    return out.length > 0 ? out : null;
  })();
  const messages = liveMessages ?? normalizeTickerMessages(config);
  const speed = config.speed === 'slow' ? 40 : config.speed === 'fast' ? 15 : 25;
  // 2026-05-03 — operator: "the ticker when I increase the font size it
  // adds some crazy scrolling text icon." The default TICKER_SEPARATOR is
  // a centered bullet (•) which becomes visually loud at large font
  // sizes. Respect the optional cfg.separator override (added in commit
  // a8f1607's editor mirror) so the operator can swap to a space, dash,
  // or empty string. Empty string → no separator at all between loops,
  // which keeps the ticker clean at huge font sizes for single messages.
  const sepRaw = typeof config.separator === 'string' ? config.separator : null;
  const sep = sepRaw === null
    ? TICKER_SEPARATOR                                    // unset → keep legacy •
    : sepRaw === ''
      ? '   '                                             // explicit empty → minimal gap
      : `     ${sepRaw}     `;                            // padded with spaces
  // Phase 3 — a live custom feed always wins over a static config.text
  // (otherwise an old single-string ticker value would mask the feed).
  const text = liveMessages
    ? liveMessages.join(sep)
    : (typeof config.text === 'string' && config.text.trim()
        ? config.text.trim()
        : messages.join(sep));
  const animation = config.scrollEnabled === false ? 'none' : `ticker-scroll ${speed}s linear infinite`;

  return (
    <div className="absolute top-0 right-0 bottom-0 left-0 flex items-center overflow-hidden" style={{ background: 'linear-gradient(90deg, #1e293b, #334155)' }}>
      <div data-inline-edit-pause style={{
        display: 'flex', whiteSpace: 'nowrap' as const,
        animation,
      }}>
        <span data-field="text" style={{ fontSize: '0.85em', fontWeight: 600, color: '#fbbf24', paddingLeft: '100%' }}>
          {text}
        </span>
        <span aria-hidden="true" style={{ fontSize: '0.85em', fontWeight: 600, color: '#fbbf24' }}>
          {sep}{text}
        </span>
      </div>
      <style>{`@keyframes ticker-scroll { 0% { transform: translateX(0); } 100% { transform: translateX(-50%); } }`}</style>
    </div>
  );
}

