/**
 * EXTERNAL_HTML — renders a self-contained HTML signage template
 * (the industry signage pack + HS district pack) in a sandboxed
 * iframe. The HTML files live under apps/web/public/templates/ and
 * are served same-path; each is a complete 3840×2160 document that
 * scales itself to the iframe via its own inline auto-fit JS.
 *
 * `sandbox="allow-scripts"` (NO allow-same-origin): the template's
 * own JS runs (needed for auto-fit + ticker scroll), but the frame
 * gets a null origin and cannot touch the parent document, cookies,
 * or storage. A broken template — parse error, runaway JS, bad CSS —
 * is fully contained to its own frame. That containment is the
 * whole point: it makes adding 78 templates a zero-risk operation
 * for the dashboard.
 */
function ExternalHtmlWidget({ config, freeze }: { config: any; freeze?: boolean }) {
  const url = typeof config?.url === 'string' ? config.url.trim() : '';

  // Passthrough payload — base64url-encoded JSON on URL params:
  //   ?brand=…       CSS custom-property overrides (colors, fonts)
  //   ?text=…        per-data-field text overrides
  //   ?textStyles=…  per-data-field inline-style overrides
  //   ?img=…         per-image-slot URL overrides (G3) — keyed by the
  //                  template's data-img / data-slot, applied as
  //                  background-image / src on the matching element.
  // The V2 shim (apps/web/scripts/inject-shim-v2.cjs) reads them all
  // and applies them at first paint. Only non-empty keys are sent so a
  // template's own defaults show through for anything the operator
  // hasn't customized.
  //
  // textStyles is the canonical source for per-field inline-style
  // overrides; cfg._styles is the source the editor's bottom-bar
  // writes to (shared with HS widgets). Send EITHER, picking the
  // canonical one first and falling back to _styles so the bottom-bar
  // experience works without operator-facing schema churn.
  const srcWithOverrides = useMemo(() => {
    if (!url) return '';
    const styles = config?.textStyles ?? config?._styles;
    const params: Array<[string, unknown]> = [
      ['brand', config?.brand],
      ['text', config?.textOverrides],
      ['textStyles', styles],
      ['img', config?.imageOverrides],
      // ?actions=… per-[data-action] button → platform touch-action map
      // ({ key: { type, target } }). The kiosk shim reads it and, on a
      // visitor tap, posts educms-action to the parent; the PLAYER runs it
      // through dispatchTouchAction (the builder preview just ignores it).
      ['actions', config?.actionOverrides],
    ];
    const segments: string[] = [];
    for (const [name, raw] of params) {
      if (!raw || typeof raw !== 'object') continue;
      // Drop empty / blank values so the template defaults show through.
      const clean: Record<string, unknown> = {};
      for (const k of Object.keys(raw)) {
        const v = (raw as Record<string, unknown>)[k];
        if (v == null) continue;
        if (typeof v === 'string' && !v.trim()) continue;
        if (typeof v === 'object' && Object.keys(v as object).length === 0) continue;
        clean[k] = v;
      }
      if (Object.keys(clean).length === 0) continue;
      try {
        const b64 = btoa(unescape(encodeURIComponent(JSON.stringify(clean))))
          .replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
        segments.push(`${name}=${b64}`);
      } catch {
        /* ignore — fall through with whatever segments did encode */
      }
    }
    let result = url;
    if (segments.length > 0) {
      const joiner = url.includes('?') ? '&' : '?';
      result = `${url}${joiner}${segments.join('&')}`;
    }
    // Gallery-grid freeze: the baked shim (EDUCMS-SHIM-V6 / EDUCMS-CLICK-V2 /
    // EDUCMS-FREEZE-V1 / kiosk _edit-shim.js) renders one auto-fit frame then
    // kills all timers + animations. Only the gallery grid passes freeze; the
    // preview modal, builder, and player render fully live.
    if (freeze) {
      result += `${result.includes('?') ? '&' : '?'}freeze=1`;
    }
    return result;
  }, [url, config?.brand, config?.textOverrides, config?.textStyles, config?._styles, config?.imageOverrides, config?.actionOverrides, freeze]);

  // ── Live menu feed (CTS-style) ──────────────────────────────────
  // QSR / restaurant / bar menu boards feed live the same way the sports
  // board does: the parent polls THIS screen's resolved menu (per-location
  // prices + auto-86 applied server-side) and postMessages it into the
  // (sandboxed, null-origin) iframe, where the V4 shim's applyMenu()
  // overlays live prices onto matching items by name — live wins where the
  // POS knows the item, the operator's static text shows otherwise (the
  // same freshness-overlay the CTS scoreboard uses). Auto-on for menu-board
  // URLs (degrades to static when no POS is connected — usePosMenuItems
  // returns null) and respects an explicit config.posSync / dataSource.
  const isMenuBoard = /\/signage\/(qsr|menus-pos|bar)\//.test(url);
  const menuDriven = isMenuBoard || config?.posSync === true || config?.dataSource === 'POS';
  // includeUnavailable: the fixed-slot HTML boards grey out 86'd items
  // (the shim's applyMenu styles them) rather than dropping them.
  const liveMenu = usePosMenuItems(menuDriven, config?.posCategory, { includeUnavailable: true });
  const frameRef = useRef<HTMLIFrameElement | null>(null);
  const postMenu = useCallback(() => {
    const win = frameRef.current?.contentWindow;
    if (!win || !Array.isArray(liveMenu) || liveMenu.length === 0) return;
    try {
      win.postMessage({ type: 'educms-overrides', menu: { items: liveMenu } }, '*');
    } catch { /* detached / cross-origin frame — ignore */ }
  }, [liveMenu]);
  // Re-post whenever the live menu changes (each 30s poll), and bind a
  // 'load' listener on the frame so the first paint (and any remount from
  // a config edit) gets the menu too. Listener is attached imperatively
  // (not a JSX onLoad) so the iframe stays a plain non-interactive element.
  useEffect(() => {
    postMenu();
    const el = frameRef.current;
    if (!el) return;
    el.addEventListener('load', postMenu);
    return () => { el.removeEventListener('load', postMenu); };
  }, [postMenu]);

  if (!url) {
    return (
      <div
        style={{
          width: '100%', height: '100%', display: 'flex',
          alignItems: 'center', justifyContent: 'center',
          background: '#0f172a', color: '#94a3b8',
          fontSize: 13, fontFamily: 'system-ui, sans-serif',
        }}
      >
        No template URL
      </div>
    );
  }
  return (
    <iframe
      // key on the full overrides URL so any edit reloads the frame.
      key={srcWithOverrides}
      ref={frameRef}
      src={srcWithOverrides}
      title="Signage template"
      loading="lazy"
      sandbox="allow-scripts"
      style={{ width: '100%', height: '100%', border: 0, display: 'block' }}
    />
  );
}

function WebpageWidget({ config, live }: { config: any; live?: boolean }) {
  // Auto-prefix bare domains with https://
  const rawUrl = config.url || '';
  // VenueOS Sports — direct mode. A same-origin page (the live
  // scoreboard at /board/<id>) must load straight in the iframe: the
  // proxy is an SSRF-guarded server-side renderer for EXTERNAL sites
  // and would serve a dead static snapshot, not a live scoreboard.
  //
  // SECURITY: `direct` is honored ONLY for our own root-relative
  // sports surfaces — /board/, /ribbon/, /scorebug/ (all built by the
  // server's scoreboard manifest). The flag lives in zone config,
  // which a template author can hand-edit (JSON editor) — so we must
  // NOT trust it to load an arbitrary URL unproxied + unsandboxed. An
  // external URL with direct:true just falls through to the proxy.
  const directMode =
    config.direct === true &&
    typeof rawUrl === 'string' &&
    (rawUrl.startsWith('/board/') ||
      rawUrl.startsWith('/ribbon/') ||
      rawUrl.startsWith('/scorebug/')) &&
    !rawUrl.includes('..');
  const url = rawUrl && !directMode && !rawUrl.startsWith('http://') && !rawUrl.startsWith('https://') && !rawUrl.startsWith('//')
    ? `https://${rawUrl}`
    : rawUrl;
  const refreshInterval = config.refreshIntervalMs || 0;
  const iframeRef = useRef<HTMLIFrameElement>(null);

  // In live mode, route through our API proxy to bypass X-Frame-Options / CSP
  // so any website can be embedded in digital signage screens.
  //
  // v1.0.16: pass interactive=true by default. Operator (2026-04-27 on
  // e-arc.com): "the URL now loads everything correctly but the top
  // area is a 5 card carousel of content and ours only shows the first
  // card and never advances." Cause: legacy strip-scripts mode froze
  // the carousel's setInterval rotator. Interactive mode lets the
  // page's own JS run inside the iframe, so rotators / accordions /
  // touch interactions all work. Operators using URL widgets are
  // typically setting up touchscreens; default to interactive.
  //
  // Allow opt-out via config.staticMode for the rare case (e.g. the
  // upstream site has runtime errors that break under iframe).
  const interactiveMode = config.staticMode !== true;
  const proxyUrl = useMemo(() => {
    if (!live || !url) return '';
    const interactiveQs = interactiveMode ? '&interactive=true' : '';
    return `${API_BASE}/api/v1/proxy/web?url=${encodeURIComponent(url)}&v=3${interactiveQs}`;
  }, [live, url, interactiveMode]);

  // Auto-refresh the iframe at the configured interval
  useEffect(() => {
    if (!live || !proxyUrl || !refreshInterval || refreshInterval < 5000) return;
    const t = setInterval(() => {
      if (iframeRef.current) {
        iframeRef.current.src = proxyUrl;
      }
    }, refreshInterval);
    return () => clearInterval(t);
  }, [live, proxyUrl, refreshInterval]);

  // Live mode — render an actual iframe routed through proxy.
  //
  // In static (script-stripped) mode the proxy already removes
  // <script> server-side, so no sandbox is needed (and adding one
  // broke the static middle of pages on 2026-04-26).
  //
  // In interactive mode (v1.0.16+) the iframe runs the upstream
  // page's JS. We still don't sandbox — sandbox=allow-scripts +
  // null-origin would CORS-break every XHR the upstream site makes
  // back to its own API. The proxy origin matches the host page,
  // and the proxy headers explicitly allow embedding (CSP frame-
  // ancestors:* + no X-Frame-Options).
  //
  // `allow` widened to include clipboard-write + accelerometer +
  // gyroscope so touch-driven sites that read device orientation /
  // copy URLs work without surfacing a permission prompt to the
  // operator (signage doesn't have a way to grant it).
  // Direct mode — render the same-origin URL straight in the iframe,
  // no proxy. Used by the VenueOS Sports scoreboard push: /board/<id>
  // is our own live, client-side page and must run unproxied. Same
  // origin means no SSRF surface and no X-Frame-Options concern.
  // Long-hand insets (not the `inset` shorthand) for Chromium-83 LED
  // controllers — see CLAUDE.md rule #10.
  if (directMode && rawUrl) {
    return (
      <div style={{ position: 'absolute', top: 0, right: 0, bottom: 0, left: 0, overflow: 'hidden' }}>
        <iframe
          ref={iframeRef}
          src={rawUrl}
          style={{ width: '100%', height: '100%', border: 0 }}
          allow="autoplay; encrypted-media; fullscreen"
          loading="eager"
          title="Scoreboard"
        />
      </div>
    );
  }

  if (live && proxyUrl) {
    return (
      <div className="absolute top-0 right-0 bottom-0 left-0 overflow-hidden">
        <iframe
          ref={iframeRef}
          src={proxyUrl}
          className="w-full h-full border-0"
          style={{ overflow: config.scrollEnabled ? 'auto' : 'hidden' }}
          allow="autoplay; encrypted-media; clipboard-write; accelerometer; gyroscope; fullscreen"
          loading="eager"
          title="Web content"
          // 2026-05-11 — operator: "i tried to use the remote control
          // with the player so I could browse through the Internet or
          // through the web URL I pushed, but the remote does not
          // move it through the different areas of the web page like
          // it does with the GoodView app. I thought we added that in
          // one of these builds already."
          //
          // The Android-side shim (apps/player/.../SpatialNavigation.kt)
          // was added 2026-05-07 but ONLY covers the fullscreen "URL
          // overlay" path on the native player. WEBPAGE widgets render
          // through this iframe instead — never touched by the native
          // shim. Inject the same shim from the React side every time
          // the iframe loads. Same-origin via /api/v1/proxy/web, so
          // contentWindow.eval is legal.
          onLoad={(e) => {
            // Lazy import keeps the shim string out of the SSR bundle.
            // The shim itself is ~3KB minified — runs entirely inside
            // the iframe, no parent dependency.
            const frame = e.currentTarget as HTMLIFrameElement;
            // 2026-06-08 (round 2) — gate the ENTIRE spatial-nav injection
            // to real full-screen DISPLAY SURFACES (kiosk player + sport
            // boards). This shim is ONLY for kiosk REMOTE-CONTROL arrow-key
            // navigation. It was being injected into every WEBPAGE iframe —
            // including dashboard live previews + template thumbnails (`live`
            // is true there too). The shim does NOT just focus once: it
            // auto-focuses an element inside the iframe on init AND re-focuses
            // it via a MutationObserver every time the iframe content mutates
            // (live clocks / animations tick constantly). On the dashboard
            // that CONTINUOUSLY pulls keyboard focus INTO the preview iframe,
            // so the operator's next click on a sidebar link first had to
            // return focus to the document — Safari/Chrome treat that as a
            // "re-activate the page" click and swallow it, so every nav button
            // needed TWO clicks and the tenant switcher went dead. (Beta
            // operator; reproduced in a private tab with a brand-new non-admin
            // user — not cache/session/role.) Gating only the final focus()
            // call (my first attempt) was not enough — the shim's own init +
            // MutationObserver focus stayed. Never inject the shim at all on
            // dashboard routes.
            const path = typeof window !== 'undefined' ? window.location.pathname : '';
            const onDisplaySurface = /^\/(player|board|overlay|ribbon|scorebug|panic)(\/|$)/.test(path);
            if (!onDisplaySurface) return;
            import('./webpage-spatial-nav').then(({ injectSpatialNav }) => {
              if (injectSpatialNav(frame)) {
                // Hand focus to the iframe so the next remote-control key
                // press lands inside it (where the shim's keydown handler is
                // bound). Display-surface only — gated above.
                try {
                  if (live && frame.contentWindow) frame.contentWindow.focus();
                } catch { /* cross-origin guard — shouldn't happen via proxy */ }
              }
            }).catch(() => { /* never block the iframe on injection */ });
          }}
        />
      </div>
    );
  }

  // Editor preview — show browser mockup
  return (
    <div className="absolute top-0 right-0 bottom-0 left-0 flex flex-col overflow-hidden" style={{ background: '#f8fafc' }}>
      {/* Browser chrome */}
      <div style={{ background: '#f1f5f9', padding: '2% 3%', display: 'flex', alignItems: 'center', gap: '2%', borderBottom: '1px solid #e2e8f0' }}>
        <div className="flex gap-[2px]">
          <div style={{ width: 5, height: 5, borderRadius: 99, background: '#fca5a5' }} />
          <div style={{ width: 5, height: 5, borderRadius: 99, background: '#fcd34d' }} />
          <div style={{ width: 5, height: 5, borderRadius: 99, background: '#86efac' }} />
        </div>
        <div style={{ flex: 1, background: 'white', borderRadius: 4, padding: '1% 3%', fontSize: '0.35em', color: '#94a3b8', overflow: 'hidden', whiteSpace: 'nowrap' as const, textOverflow: 'ellipsis' }}>
          {url || 'https://...'}
        </div>

      </div>
      <div className="flex-1 flex items-center justify-center">
        <div className="text-center">
          <Globe style={{ width: '1.5em', height: '1.5em', color: '#10b981', opacity: 0.4, margin: '0 auto' }} />
          <div style={{ fontSize: '0.45em', color: '#94a3b8', marginTop: '0.3em' }}>{url ? 'Web content will load here' : 'Set URL in properties'}</div>
        </div>
      </div>
    </div>
  );
}

