package com.educms.player.media

import org.json.JSONArray
import org.json.JSONObject

/*
 * THE APP OWNS THE PLAYBACK SESSION — the pure half (design
 * docs/design/NATIVE-FIRST-ONE-STORE.md §3.3–§3.5 and §4, native-first stream B,
 * 2026-10-19). Everything in this file is free of android.* and unit-tested
 * (PlaybackLeaseTest, NativeFirstBoundaryTest); FaceVideoBox is the Android
 * half that acts on these decisions.
 *
 *  • PROTOCOL 4 rides the EXISTING `sharedVideoPrepare` (CLAUDE.md player rule
 *    9: no new bridge method). A `version: 4` message carries an `op`:
 *      {version:4, op:"intend",  screenId, revision, sha256, assetId, start:"now"|"boundary", lease}
 *      {version:4, op:"release", lease, at:"now"|"boundary"}
 *      {version:4, op:"sync",    manifestTag, emergencySetHash?}
 *    Identity only — never a URL, never a token. `sharedVideoCommit` /
 *    `sharedVideoStop` are unchanged and keep serving v2 / v3 sessions.
 *  • THE LEASE (§4.1) is the page's liveness, NOT a condition for presenting.
 *    Every `sharedVideoState` poll renews it; it is absent AT ONCE on a
 *    main-frame document change or a renderer loss, otherwise 10 s after the
 *    last renewal. An absent lease moves the session to UNATTENDED: it keeps
 *    presenting, and the native alert watch switches to its fast cadence
 *    (§7 E4). Each page document generates its own lease id; the first v4
 *    message of a new document ADOPTS the face (retiring the previous id), and
 *    a lease a retired document wrote can never act again.
 *  • THE INTENT (§4.1) — one per face: identity, start policy, the lease that
 *    wrote it and when — is persisted in app-private storage on every accepted
 *    change, so it survives a reload, a WebView replacement and a process
 *    death. Owner decision D5: NOTHING here changes content on its own. The
 *    page is the one controller; the app keeps presenting the last intent and
 *    reports what it holds (`intent` on the state reply) — a suspended or
 *    ended intent is restarted only by the page's next `intend` (§4.3).
 */

/** When a v4 intent (or a release) takes effect. */
internal enum class StartPolicy(val wire: String) {
    /** As soon as the file is ready (an `intend`), or at once (a `release`). */
    NOW("now"),
    /** At the presenting session's next loop end, bounded by [NativeFirstBoundary.BOUNDARY_WAIT_MS]. */
    BOUNDARY("boundary");

    companion object {
        fun parse(v: String?): StartPolicy? = values().firstOrNull { it.wire == v }
    }
}

/** Every version-4 message the page may send on `sharedVideoPrepare`. */
internal sealed class NativeFirstMessage {
    /** This face's solo intent; it replaces the previous one. */
    data class Intend(
        val screenId: String, val revision: String, val sha256: String, val assetId: String,
        val start: StartPolicy, val lease: String,
    ) : NativeFirstMessage() {
        /** The same session for the page: identity, never geometry or policy. */
        val identity: List<String> get() = listOf(screenId, revision, sha256, assetId)
        fun request(): FaceVideoRequest = FaceVideoRequest(screenId, revision, sha256, assetId)
    }

    /** No solo native content on this face; the page's web content is painted beneath. */
    data class Release(val lease: String, val at: StartPolicy) : NativeFirstMessage()

    /** A nudge: the page applied a new manifest / emergency set. Carries no lease (it changes nothing on the glass). */
    data class Sync(val manifestTag: String, val emergencySetHash: String?) : NativeFirstMessage()

    companion object {
        const val VERSION = 4
        private val uuid = Regex("[a-fA-F0-9]{8}(?:-[a-fA-F0-9]{4}){3}-[a-fA-F0-9]{12}")
        private val digest = Regex("[a-f0-9]{64}")
        /** A page document's lease id: generated by the page, opaque to the app. */
        val LEASE = Regex("[A-Za-z0-9_-]{8,64}")
        /** Printable ASCII without spaces (an ETag-like value is fine). */
        private val TAG = Regex("[\\x21-\\x7e]{1,128}")
        private val SET_HASH = Regex("[A-Za-z0-9_.:-]{1,128}")
        /** Native reads URLs and credentials from its OWN authenticated sources, never from the page. */
        val FORBIDDEN_KEYS = listOf("url", "src", "token", "authorization", "cookie")

        /** Null for anything that is not a well-formed version-4 message. Fail closed. */
        fun parse(json: String): NativeFirstMessage? = runCatching {
            require(json.length <= 1024)
            val j = JSONObject(json)
            require(j.getInt("version") == VERSION)
            // Identity only: a message that tries to hand native a URL or a credential is refused whole.
            require(FORBIDDEN_KEYS.none { j.has(it) })
            when (j.getString("op")) {
                "intend" -> {
                    val m = Intend(
                        j.getString("screenId"), j.getString("revision"), j.getString("sha256").lowercase(),
                        j.getString("assetId"), StartPolicy.parse(j.getString("start")) ?: error("start"), j.getString("lease"),
                    )
                    require(uuid.matches(m.screenId) && uuid.matches(m.assetId))
                    require(m.revision.length in 1..128 && digest.matches(m.sha256) && LEASE.matches(m.lease))
                    m
                }
                "release" -> Release(
                    j.getString("lease").also { require(LEASE.matches(it)) },
                    StartPolicy.parse(j.getString("at")) ?: error("at"),
                )
                "sync" -> Sync(
                    j.getString("manifestTag").also { require(TAG.matches(it)) },
                    if (j.isNull("emergencySetHash") || !j.has("emergencySetHash")) null
                    else j.getString("emergencySetHash").also { require(SET_HASH.matches(it)) },
                )
                else -> error("op")
            }
        }.getOrNull()
    }
}

/**
 * One face's page lease (§4.1). Pure: every clock read is passed in
 * (`elapsedRealtime`). Guarded by the caller's monitor (FaceVideoBox).
 */
internal class PlaybackLease(createdAtMs: Long, private val boundMs: Long = BOUND_MS) {
    enum class Verdict {
        /** The live document spoke again. */
        RENEWED,
        /** A new document took the face over; any previous lease id is retired. */
        ADOPTED,
        /** A lease a retired document wrote: it can never act again. */
        RETIRED,
    }

    /** The live document's lease id, or null when no document holds the face. */
    var id: String? = null
        private set
    private var renewedAtMs = Long.MIN_VALUE
    private var adoptedAtMs = Long.MIN_VALUE
    private var absentFromMs: Long = createdAtMs
    private val retired = ArrayDeque<String>()
    /** Documents that have adopted this face, for the ledger. */
    var adoptions = 0L
        private set

    fun accept(lease: String, nowMs: Long): Verdict {
        if (lease in retired) return Verdict.RETIRED
        if (lease == id) {
            renewedAtMs = nowMs
            return Verdict.RENEWED
        }
        id?.let { retireId(it) }
        id = lease
        renewedAtMs = nowMs
        adoptedAtMs = nowMs
        adoptions++
        return Verdict.ADOPTED
    }

    /**
     * A main-frame document callback (MainActivity / FacePlayerHost
     * `onMainFrameDocument`). It fires up to THREE times for one navigation —
     * page started, commit visible, page finished — and the new document's
     * script can adopt the face between the first and the last. So a lease
     * adopted within [DOCUMENT_SHIELD_MS] belongs to the document now loading
     * and is NOT retired by that same navigation's later callbacks; anything
     * older is the outgoing document's, and is retired at once. True when it
     * retired a lease.
     */
    fun onDocumentChange(nowMs: Long): Boolean {
        if (id == null || nowMs - adoptedAtMs < DOCUMENT_SHIELD_MS) return false
        retire(nowMs)
        return true
    }

    /** A `sharedVideoState` poll. Renews the live document's lease; true when there was one to renew. */
    fun renew(nowMs: Long): Boolean {
        if (id == null) return false
        renewedAtMs = nowMs
        return true
    }

    /** A main-frame document change or a renderer loss: the lease is absent AT ONCE, and its id can never act again. */
    fun retire(nowMs: Long) {
        val was = id ?: return
        retireId(was)
        id = null
        absentFromMs = nowMs
    }

    fun live(nowMs: Long): Boolean = id != null && nowMs - renewedAtMs <= boundMs

    /** When the lease became absent, or null while it is live. */
    fun absentSince(nowMs: Long): Long? = when {
        live(nowMs) -> null
        id != null -> renewedAtMs + boundMs
        else -> absentFromMs
    }

    /** `elapsedRealtime` age of the last renewal, or -1 when no document holds the face. */
    fun ageMs(nowMs: Long): Long = if (id == null) -1L else (nowMs - renewedAtMs).coerceAtLeast(0L)

    private fun retireId(lease: String) {
        retired.addLast(lease)
        while (retired.size > RETIRED_MAX) retired.removeFirst()
    }

    companion object {
        /** A lease not renewed for this long is absent (the page polls every 500 ms while a session matters). */
        const val BOUND_MS = 10_000L
        /** A lease adopted this recently belongs to the document still loading (onDocumentChange). */
        const val DOCUMENT_SHIELD_MS = 30_000L
        /** Retired ids remembered; a document that old cannot still be speaking. */
        const val RETIRED_MAX = 16
    }
}

/** The face's solo intent (§4.1). Wall-clock `atMs`: it is persisted and must survive a reboot. */
internal data class PlaybackIntent(
    val screenId: String, val revision: String, val sha256: String, val assetId: String,
    val start: StartPolicy, val lease: String, val atMs: Long,
    /** An emergency hold ended the session; the intent waits for the page's restore (§4.2, §4.3). */
    val suspendedByHold: Boolean = false,
) {
    val identity: List<String> get() = listOf(screenId, revision, sha256, assetId)
    fun request(): FaceVideoRequest = FaceVideoRequest(screenId, revision, sha256, assetId)

    fun toJson(): JSONObject = JSONObject().put("v", 1)
        .put("screenId", screenId).put("revision", revision).put("sha256", sha256).put("assetId", assetId)
        .put("start", start.wire).put("lease", lease).put("atMs", atMs).put("suspendedByHold", suspendedByHold)

    companion object {
        fun of(m: NativeFirstMessage.Intend, atMs: Long): PlaybackIntent =
            PlaybackIntent(m.screenId, m.revision, m.sha256, m.assetId, m.start, m.lease, atMs)

        /** Null for anything that would not have been accepted as an `intend` (a damaged store reads as no intent). */
        fun parse(raw: String?): PlaybackIntent? = runCatching {
            val j = JSONObject(raw ?: return null)
            require(j.getInt("v") == 1)
            val m = NativeFirstMessage.parse(
                JSONObject().put("version", NativeFirstMessage.VERSION).put("op", "intend")
                    .put("screenId", j.getString("screenId")).put("revision", j.getString("revision"))
                    .put("sha256", j.getString("sha256")).put("assetId", j.getString("assetId"))
                    .put("start", j.getString("start")).put("lease", j.getString("lease")).toString(),
            ) as? NativeFirstMessage.Intend ?: return null
            of(m, j.getLong("atMs")).copy(suspendedByHold = j.optBoolean("suspendedByHold", false))
        }.getOrNull()
    }
}

/** Where intents are persisted. Android: one SharedPreferences file, `commit()` (FaceVideoBox). Tests: a map. */
internal interface IntentStore {
    fun read(face: Int): String?
    /** Null removes. True when the write reached storage. */
    fun write(face: Int, value: String?): Boolean
}

/** The per-face intents, memoised over [IntentStore]. Guarded by the caller's monitor. */
internal class PlaybackIntents(private val store: IntentStore) {
    private val memo = HashMap<Int, PlaybackIntent?>()

    fun get(face: Int): PlaybackIntent? = memo.getOrPut(face) { PlaybackIntent.parse(runCatching { store.read(face) }.getOrNull()) }

    /** Persist on every accepted change (§4.1). */
    fun put(face: Int, intent: PlaybackIntent?): Boolean {
        if (memo.containsKey(face) && memo[face] == intent) return true
        memo[face] = intent
        return runCatching { store.write(face, intent?.toJson()?.toString()) }.getOrDefault(false)
    }

    /** A process restart: forget the memo, read storage again. */
    fun reload() = memo.clear()
}

/**
 * What ends a v4 session, and what happens to the intent (§4.2). One table,
 * consulted by FaceVideoBox — the test reads the same table, so a test can
 * never pass while the engine does something else.
 */
internal object PlaybackSessionPolicy {
    enum class Event {
        /** A reload, a Resync, a bundle apply, a wedge reload. */
        DOCUMENT_CHANGED,
        /** The page stopped polling for [PlaybackLease.BOUND_MS]. */
        PAGE_SILENT,
        /** The WebView renderer died and the WebView was replaced. */
        RENDERER_LOST,
        /** A live page polls but never adopted a presenting session within [ADOPT_GRACE_MS] (it does not speak v4). */
        UNADOPTED,
        RELEASED,
        /** The page intended other content: this session gave way. */
        INTENT_CHANGED,
        EMERGENCY_HOLD,
        OPERATOR_UI,
        LIFECYCLE_NOT_READY,
        ACTIVITY_PAUSED,
        CREDENTIAL_IDENTITY,
        /** Any other end of the closed set, graded by [NativeEndReasons]. */
        OTHER_END,
    }

    enum class Outcome {
        /** Nothing happens on the glass; the lease is absent (unattended) and the alert watch speeds up. */
        CONTINUE_UNATTENDED,
        /** The session moves to the replacement WebView's host; its surface lives in the root layout. */
        REHOME,
        /** The session ends; the intent stays for the page to restart (§4.3). */
        END_KEEP_INTENT,
        /** The session ends; the intent is kept as suspended-by-hold until the page restores it. */
        END_SUSPEND_INTENT,
        /** The session ends and the intent is gone. */
        END_DISCARD_INTENT,
    }

    /** A live page that polls but has not adopted a presenting v4 session for this long is not its controller. */
    const val ADOPT_GRACE_MS = 60_000L

    /** What an `intend` does (§3.5, §4.3). FaceVideoBox.intend acts on exactly this. */
    enum class IntendAction {
        /** The same content presents / prepares: the new lease takes it over; nothing happens on the glass. */
        ADOPT,
        /** The same content is already pre-rolling: only its start policy is updated. */
        ADOPT_NEXT,
        /** A new content and something presents: it pre-rolls and swaps at the boundary (§3.3). */
        PREROLL,
        /** A new content (or a restore of a suspended / ended one) and nothing presents: it starts. */
        START,
        /** An emergency hold is raised: nothing starts; the intent is kept, suspended (§7 E2). */
        SUSPEND,
        /** Native-first is off for this face (a flip never ends what presents — that is an ADOPT). */
        REFUSE_SWITCH_OFF,
        /** The app's own 24 h block of this file on this face and build is live. */
        REFUSE_BLOCKED,
    }

    /**
     * The decision, in order: an ADOPT outranks everything (a switch flip or a
     * block never restarts what presents); then the switch, the block and the
     * hold are checked before anything may start; then the boundary.
     */
    fun onIntend(
        sameAsCurrent: Boolean, sameAsNext: Boolean, currentPresenting: Boolean,
        switchOn: Boolean, blocked: Boolean, held: Boolean,
    ): IntendAction = when {
        sameAsCurrent -> IntendAction.ADOPT
        sameAsNext -> IntendAction.ADOPT_NEXT
        !switchOn -> IntendAction.REFUSE_SWITCH_OFF
        blocked -> IntendAction.REFUSE_BLOCKED
        held -> IntendAction.SUSPEND
        currentPresenting -> IntendAction.PREROLL
        else -> IntendAction.START
    }

    /** §4.2 for a version-4 session. */
    fun v4(event: Event, rehomeable: Boolean = true, reason: String? = null): Outcome = when (event) {
        Event.DOCUMENT_CHANGED, Event.PAGE_SILENT -> Outcome.CONTINUE_UNATTENDED
        Event.RENDERER_LOST -> if (rehomeable) Outcome.REHOME else Outcome.END_KEEP_INTENT
        Event.EMERGENCY_HOLD -> Outcome.END_SUSPEND_INTENT
        Event.RELEASED, Event.UNADOPTED, Event.CREDENTIAL_IDENTITY -> Outcome.END_DISCARD_INTENT
        Event.INTENT_CHANGED, Event.OPERATOR_UI, Event.LIFECYCLE_NOT_READY, Event.ACTIVITY_PAUSED -> Outcome.END_KEEP_INTENT
        Event.OTHER_END -> fateOf(reason ?: "native-prepare")
    }

    /** Today's (v2 / v3) behaviour, kept for contrast: every one of these ends the session. */
    fun v2(event: Event): Outcome = when (event) {
        Event.EMERGENCY_HOLD -> Outcome.END_SUSPEND_INTENT
        else -> Outcome.END_DISCARD_INTENT
    }

    /** What a v4 end with [reason] (any raw or closed code) does to the intent. */
    fun fateOf(reason: String): Outcome {
        val code = NativeEndReasons.normalize(reason)
        return when {
            code == "emergency-held" -> Outcome.END_SUSPEND_INTENT
            code in DISCARDING -> Outcome.END_DISCARD_INTENT
            NativeEndReasons.isFault(code) || NativeEndReasons.isRefused(code) -> Outcome.END_DISCARD_INTENT
            else -> Outcome.END_KEEP_INTENT
        }
    }

    /** The closed-set code a v4 end of [event] reports. */
    fun reason(event: Event): String? = when (event) {
        Event.DOCUMENT_CHANGED, Event.UNADOPTED -> "document-retired"
        Event.PAGE_SILENT -> "page-lease-expired"
        Event.RENDERER_LOST -> "host-replaced"
        Event.RELEASED -> "released"
        Event.INTENT_CHANGED -> "content-changed"
        Event.EMERGENCY_HOLD -> "emergency-held"
        Event.OPERATOR_UI -> "operator-ui"
        Event.LIFECYCLE_NOT_READY -> "lifecycle-not-ready"
        Event.ACTIVITY_PAUSED -> "activity-paused"
        Event.CREDENTIAL_IDENTITY -> "credential-identity"
        Event.OTHER_END -> null
    }

    /** Ends that are deliberate (an alert, the operator, the page itself): they never count toward settling (§3.4). */
    val DELIBERATE: Set<String> = setOf(
        "emergency-held", "released", "content-changed", "superseded", "page-requested", "operator-ui",
        "document-retired", "page-stopped",
    )

    private val DISCARDING = setOf("released", "credential-identity", "document-retired")
}

/**
 * THE NATIVE → NATIVE BOUNDARY SWITCH (§3.3), as decisions. FaceVideoBox
 * runs the steps; this decides which, in what order, and never lets a raised
 * emergency hold put anything on the glass.
 */
internal object NativeFirstBoundary {
    enum class Path {
        /** B prepares beside A — surface, decoder, a HELD first frame — and is released at the swap. */
        PREROLL,
        /** A second decoder was refused: A's surface keeps its last frame, A's decoder is released, B starts and is revealed on its first frame. */
        HOLD_LAST_FRAME,
    }

    enum class Step {
        /** The hold is raised: nothing moves onto the glass (suppression has already ended both sessions). */
        ABORT_HELD,
        /** Stop A's decoder; its surface keeps the last frame it showed. */
        FREEZE_A,
        /** Let B's held first frame go: its clock starts now. */
        RELEASE_B,
        /** Start B's decoder (the hold-last-frame path). */
        START_B,
        /** B goes through the ordinary reveal (above the window, confirmed by a post-request render). */
        REVEAL_B,
        /** A's views go only once B's first post-reveal render confirms: never a black frame between them. */
        REMOVE_A_ON_CONFIRM,
    }

    /** How long a `boundary` start (or release) waits for A's loop end once B is ready — today's handoff bound. */
    const val BOUNDARY_WAIT_MS = 60_000L

    /**
     * Pre-roll when the decoder budget — counted across EVERY face — allows
     * one more decoder one early (the picture on the glass always wins the
     * last decoder, [FaceZonePolicy.decoderAllowed]); otherwise hold A's last
     * frame.
     */
    fun path(decodersElsewhere: Int, advertisedInstances: Int): Path =
        if (FaceZonePolicy.decoderAllowed(decodersElsewhere, advertisedInstances, preroll = true)) Path.PREROLL else Path.HOLD_LAST_FRAME

    /** Is the swap due? B must be ready; `now` swaps at once, `boundary` at A's loop end or the bound. */
    fun swapDue(start: StartPolicy, bReady: Boolean, aAtLapEnd: Boolean, bReadyAtMs: Long, nowMs: Long): Boolean =
        bReady && (start == StartPolicy.NOW || aAtLapEnd || (bReadyAtMs > 0L && nowMs - bReadyAtMs >= BOUNDARY_WAIT_MS))

    /**
     * The swap pass, in order. ⚠️ THE HOLD IS CHECKED FIRST (§7 E1): a raised
     * hold returns [Step.ABORT_HELD] alone and nothing reaches the glass.
     */
    fun swapSteps(held: Boolean, path: Path): List<Step> {
        if (held) return listOf(Step.ABORT_HELD)
        return listOf(
            Step.FREEZE_A,
            if (path == Path.PREROLL) Step.RELEASE_B else Step.START_B,
            Step.REVEAL_B,
            Step.REMOVE_A_ON_CONFIRM,
        )
    }
}

/**
 * The 24 h block of a real fault of a verified file (§3.4), keyed by file +
 * face + APK build, persisted (wall clock: it must survive a reboot). Pure
 * over [Kv]; FaceVideoBox stores it in SharedPreferences.
 */
internal class NativeFaultBlocks(private val kv: Kv, private val build: String) {
    interface Kv {
        fun get(): String?
        fun put(value: String)
    }

    fun blockedUntil(sha256: String, face: Int, nowMs: Long): Long? {
        val until = read().optLong(key(sha256, face, build), 0L)
        return if (until > nowMs) until else null
    }

    fun block(sha256: String, face: Int, nowMs: Long) {
        val all = read()
        val out = JSONObject()
        // Expired entries go; the newest [MAX] stay.
        all.keys().asSequence().map { it to all.optLong(it, 0L) }.filter { it.second > nowMs }
            .sortedByDescending { it.second }.take(MAX - 1).forEach { out.put(it.first, it.second) }
        out.put(key(sha256, face, build), nowMs + BLOCK_MS)
        runCatching { kv.put(out.toString()) }
    }

    private fun read(): JSONObject = runCatching { JSONObject(kv.get() ?: "{}") }.getOrDefault(JSONObject())

    companion object {
        const val BLOCK_MS = 24L * 60 * 60 * 1000
        const val MAX = 32
        fun key(sha256: String, face: Int, build: String): String = "${sha256.lowercase()}:$face:$build"
    }
}

/** `sync` is rate-limited and single-flight (§3.5): the latest tag wins, at most one run per [minIntervalMs]. */
internal class SyncGate(private val minIntervalMs: Long = MIN_INTERVAL_MS) {
    private var lastRunAtMs = Long.MIN_VALUE / 2
    private var running = false
    private var pending: NativeFirstMessage.Sync? = null

    /** True when the caller should run [m] now; otherwise it is kept (latest wins) for [done]. */
    @Synchronized fun offer(m: NativeFirstMessage.Sync, nowMs: Long): Boolean {
        if (running || nowMs - lastRunAtMs < minIntervalMs) {
            pending = m
            return false
        }
        running = true
        lastRunAtMs = nowMs
        return true
    }

    /** The run finished; returns the newest message that arrived meanwhile (to offer again after the interval). */
    @Synchronized fun done(): NativeFirstMessage.Sync? {
        running = false
        return pending.also { pending = null }
    }

    /** A rate-limited message waiting for its turn (null when a run will pick it up, or none waits). */
    @Synchronized fun takePending(): NativeFirstMessage.Sync? = if (running) null else pending.also { pending = null }

    companion object {
        const val MIN_INTERVAL_MS = 2_000L
    }
}

/**
 * The bridge's reply bound (the page refuses a `sharedVideoState` longer than
 * 16 384 characters). Trims the bulkiest, least essential parts first: the
 * per-session timing history inside `sessions[]`, then the top level's, then
 * the store's sha lists. Never touches state, reasons, lease or intent.
 */
internal object ReplyBudget {
    const val MAX_CHARS = 15_360

    fun fit(j: JSONObject, max: Int = MAX_CHARS): JSONObject {
        if (j.toString().length <= max) return j
        j.optJSONArray("sessions")?.let { a ->
            for (i in 0 until a.length()) a.optJSONObject(i)?.optJSONObject("timing")?.remove("history")
        }
        if (j.toString().length <= max) return j
        j.optJSONObject("timing")?.remove("history")
        if (j.toString().length <= max) return j
        j.optJSONObject("store")?.let { s ->
            for (key in listOf("pending", "ready")) {
                val arr = s.optJSONArray(key) ?: continue
                val cut = JSONArray()
                for (i in 0 until minOf(arr.length(), 8)) cut.put(arr.opt(i))
                s.put(key, cut).put("${key}Truncated", true)
            }
        }
        if (j.toString().length <= max) return j
        j.optJSONArray("sessions")?.let { a ->
            for (i in 0 until a.length()) a.optJSONObject(i)?.remove("timing")
        }
        return j
    }
}
